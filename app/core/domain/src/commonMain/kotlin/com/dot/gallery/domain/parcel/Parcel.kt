package com.dot.gallery.domain.parcel


/**
 * Multiplatform `Parcelable` — on Android this is `android.os.Parcelable`,
 * elsewhere an empty marker. Models implement it so navigation/Bundle code
 * keeps working on Android while commonMain stays portable.
 */
expect interface Parcelable

@OptIn(ExperimentalMultiplatform::class)
@OptionalExpectation
@Target(AnnotationTarget.CLASS)
@Retention(AnnotationRetention.BINARY)
expect annotation class Parcelize()

@OptIn(ExperimentalMultiplatform::class)
@OptionalExpectation
@Target(AnnotationTarget.PROPERTY)
@Retention(AnnotationRetention.SOURCE)
expect annotation class IgnoredOnParcel()
